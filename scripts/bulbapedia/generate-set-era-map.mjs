import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ERA_CONFIGS } from './era-config.mjs';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const ERA_IDS = Object.keys(ERA_CONFIGS);
const OUTPUT_PATH = resolve(PROJECT_ROOT, 'data/bulbapedia/set-era-map.js');

// Printed set codes keep their punctuation (e.g. "XY-P", "S-P"), matching the
// runtime resolver's code normalization.
function normalizeSetCode(value) {
  return typeof value === 'string' ? value.trim().toUpperCase() || null : null;
}

// Set names become SHOUTING_SNAKE so a misread code can still find the era.
function normalizeSetName(value) {
  if (typeof value !== 'string') return null;
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_|_$/g, '') || null;
}

// Every set code, TCGdex set id, and set name that appears on either side of a
// relationship (both directions, records and enToJa).
function collectEraKeys(index) {
  const keys = new Set();
  const sides = [];
  for (const record of Object.values(index.records || {})) {
    sides.push(record.source);
    for (const target of record.targets || []) sides.push(target);
  }
  for (const record of Object.values(index.enToJa || {})) {
    sides.push(record.source);
    for (const target of record.targets || []) sides.push(target);
  }
  for (const side of sides) {
    if (!side) continue;
    for (const value of [side.setCode, side.tcgdexSetId]) {
      const code = normalizeSetCode(value);
      if (code) keys.add(code);
    }
    const name = normalizeSetName(side.setName);
    if (name) keys.add(name);
  }
  return keys;
}

function renderMapSource(map) {
  const lines = Object.keys(map).sort().map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(map[key])},`);
  return [
    '// Generated by scripts/bulbapedia/generate-set-era-map.mjs - do not edit by hand.',
    '// Maps a printed set code or set name to the era bundle(s) that contain it, so',
    '// the runtime injects only the era a scan needs instead of all of them.',
    'const BULBAPEDIA_SET_ERA_MAP = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

async function main() {
  const map = {};
  for (const eraId of ERA_IDS) {
    const indexPath = resolve(PROJECT_ROOT, `data/bulbapedia/${eraId}/counterpart-index.json`);
    const index = JSON.parse(await readFile(indexPath, 'utf8'));
    for (const key of collectEraKeys(index)) {
      map[key] = map[key] || [];
      if (!map[key].includes(eraId)) map[key].push(eraId);
    }
  }
  await writeFile(OUTPUT_PATH, renderMapSource(map), 'utf8');
  console.log(`Wrote ${OUTPUT_PATH} (${Object.keys(map).length} keys)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
